#!/usr/bin/env node
/**
 * Copy the customer-facing docs into the platform package before it is built.
 *
 * ## Why a copy step rather than an asset path
 *
 * ng-packagr refuses assets from outside the package root — established by trying it:
 * "Cannot read assets from a location outside of the project root." So
 * `docs/extension-reference.md` cannot be listed in `libs/platform/ng-package.json`
 * directly.
 *
 * ## Why not just keep a second copy in libs/platform
 *
 * Because that is two copies of the customer contract, and this repository has just
 * finished paying for a document that disagreed with the code. A checked-in duplicate
 * would drift, and the drift gate watches `docs/extension-reference.md`, not the copy.
 * One source, copied at build time, cannot disagree with itself.
 *
 * The copies are gitignored and carry a generated banner, so an edit to the wrong file
 * is obvious and is overwritten on the next build rather than silently kept.
 *
 * Usage:
 *   node scripts/sync-platform-docs.mjs            # copy
 *   node scripts/sync-platform-docs.mjs --check    # verify the copies are current
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve, basename } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const PACKAGE_ROOT = join(ROOT, 'libs', 'platform');

/** Source of truth -> filename inside the package. */
const DOCS = ['docs/extension-reference.md'];

const banner = (source) =>
  `<!--\n` +
  `  GENERATED — do not edit this file.\n\n` +
  `  Copied from ${source} by scripts/sync-platform-docs.mjs when the platform\n` +
  `  package is built, so the published contract cannot drift from the one the\n` +
  `  repository gates. Edit the source; this copy is overwritten.\n` +
  `-->\n\n`;

const check = process.argv.includes('--check');
const problems = [];
let written = 0;

for (const relative of DOCS) {
  const source = join(ROOT, relative);
  if (!existsSync(source)) {
    problems.push(`${relative} does not exist, but the platform package expects to ship it.`);
    continue;
  }
  const target = join(PACKAGE_ROOT, basename(relative));
  const expected = banner(relative) + readFileSync(source, 'utf8');

  if (check) {
    const actual = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (actual !== expected) {
      problems.push(
        `${basename(relative)} in the package is ${actual === null ? 'missing' : 'stale'}. ` +
          'Run `node scripts/sync-platform-docs.mjs`.',
      );
    }
    continue;
  }

  writeFileSync(target, expected);
  written += 1;
}

if (problems.length) {
  console.error(`\nsync-platform-docs: FAIL\n`);
  for (const p of problems) console.error(`- ${p}`);
  console.error('');
  process.exit(1);
}

console.log(
  check
    ? `sync-platform-docs: pass — ${DOCS.length} doc(s) in the package match their source.`
    : `sync-platform-docs: copied ${written} doc(s) into libs/platform.`,
);
